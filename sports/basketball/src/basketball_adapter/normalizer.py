def normalize_russian_basketball_team(raw_name: str) -> str:
    """
    Normalizes a Russian basketball team name to its canonical form.
    Strips noise, bracketed seeds, prefixes, and matches canonical dictionary.
    """
    if not raw_name or not isinstance(raw_name, str):
        return "Неизвестная команда"

    name = raw_name.strip()

    # 1. Strip bracketed text like [1], (рез), (мол), (W), (ж)
    name = re.sub(r"\[.*?\]", "", name)
    name = re.sub(r"\(.*?\)", "", name)

    # 2. Strip leading numbers or dots
    name = re.sub(r"^\d+[\.\s]+", "", name)

    # 3. Strip redundant punctuation
    name = re.sub(r"[\*#]+", "", name).strip()

    # 4. Collapse whitespaces
    name = re.sub(r"\s+", " ", name).strip()

    # 5. Check dictionary lookup (case-insensitive)
    key = name.lower()
    if key in CANONICAL_BASKETBALL_TEAMS:
        return CANONICAL_BASKETBALL_TEAMS[key]

    # Partial substring check
    for k, canonical in CANONICAL_BASKETBALL_TEAMS.items():
        if key == k or key.startswith(k + " ") or key.endswith(" " + k):
            return canonical

    # If no mapping, return title-cased clean name
    return name.title() if not name.isupper() else name
