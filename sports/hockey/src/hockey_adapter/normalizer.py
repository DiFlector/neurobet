def normalize_russian_hockey_team(raw_name: str) -> str:
    """
    Normalizes a Russian hockey team name into its canonical form.
    Strips noise, punctuation, and common suffixes/prefixes (e.g., 'ХК').
    """
    if not raw_name:
        return ""

    cleaned = str(raw_name).strip()
    # Remove city/country parenthesis if any, e.g. "ЦСКА (Москва)"
    cleaned = re.sub(r"\s*\([^)]*\)", "", cleaned).strip()

    # Look up in lowercase
    lookup_key = cleaned.lower()
    if lookup_key in HOCKEY_TEAMS_RU:
        return HOCKEY_TEAMS_RU[lookup_key]

    # Try removing leading "хк "
    if lookup_key.startswith("хк "):
        sub_key = lookup_key[3:].strip()
        if sub_key in HOCKEY_TEAMS_RU:
            return HOCKEY_TEAMS_RU[sub_key]

    return cleaned
