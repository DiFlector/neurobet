def normalize_russian_football_team(raw_name: str) -> str:
    """
    Normalizes a football team name into its canonical form.
    Strips noise, punctuation, and common suffixes/prefixes (e.g., 'ФК', 'FC', 'ПФК').
    """
    if not raw_name:
        return ""

    cleaned = str(raw_name).strip()
    # Remove city/country parenthesis if any, e.g. "Спартак (Москва)"
    cleaned = re.sub(r"\s*\([^)]*\)", "", cleaned).strip()

    # Look up in lowercase
    lookup_key = cleaned.lower()
    if lookup_key in FOOTBALL_TEAMS_RU:
        return FOOTBALL_TEAMS_RU[lookup_key]

    # Try removing leading "фк ", "пфк ", "fc "
    for prefix in ("фк ", "пфк ", "fc "):
        if lookup_key.startswith(prefix):
            sub_key = lookup_key[len(prefix):].strip()
            if sub_key in FOOTBALL_TEAMS_RU:
                return FOOTBALL_TEAMS_RU[sub_key]

    return cleaned
