import uuid
from datetime import datetime
from typing import Optional, Dict, Any
from sqlalchemy import String, Boolean, Numeric, DateTime, ForeignKey, Index
from sqlalchemy.dialects.postgresql import UUID, JSONB
from sqlalchemy.orm import Mapped, mapped_column
from ..base import Base, UUIDPrimaryKeyMixin, utc_now


class FeatureSnapshot(Base):
    """
    TimescaleDB Hypertable partitioned on observed_at.
    Stores historical point-in-time feature vectors guaranteed without future data leakage.
    """
    __tablename__ = "feature_snapshots"

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    observed_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), primary_key=True, default=utc_now)
    event_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), nullable=False)
    sport_code: Mapped[str] = mapped_column(String(32), default="tennis", nullable=False)
    feature_version: Mapped[str] = mapped_column(String(32), default="1.0.0", nullable=False)
    features: Mapped[Dict[str, Any]] = mapped_column(JSONB, default=dict, nullable=False)

    __table_args__ = (
        Index("idx_feature_snapshots_event_time", "event_id", "observed_at"),
    )


class MLPrediction(Base, UUIDPrimaryKeyMixin):
    """
    Predictions generated by numeric ML models for match events.
    Matches user requirements for Tennis edge and expected value tracking.
    """
    __tablename__ = "ml_predictions"

    event_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("events.id", ondelete="CASCADE"), nullable=False)
    sport_code: Mapped[str] = mapped_column(String(32), default="tennis", nullable=False)
    model_version: Mapped[str] = mapped_column(String(64), nullable=False)
    market: Mapped[str] = mapped_column(String(64), default="match_winner", nullable=False)

    predicted_outcome: Mapped[str] = mapped_column(String(64), nullable=False)
    model_probability: Mapped[float] = mapped_column(Numeric(6, 4), nullable=False)
    bookmaker_odds: Mapped[float] = mapped_column(Numeric(10, 4), nullable=False)
    fair_odds: Mapped[float] = mapped_column(Numeric(10, 4), nullable=False)
    edge: Mapped[float] = mapped_column(Numeric(8, 4), nullable=False)
    expected_value: Mapped[float] = mapped_column(Numeric(8, 4), nullable=False)
    confidence: Mapped[float] = mapped_column(Numeric(6, 4), nullable=False)

    has_positive_edge: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    is_shadow: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    outcomes_detail: Mapped[Dict[str, Any]] = mapped_column(JSONB, default=dict, nullable=False)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utc_now, nullable=False)

    __table_args__ = (
        Index("idx_ml_predictions_event", "event_id", "created_at"),
        Index("idx_ml_predictions_edge", "has_positive_edge", "created_at"),
        Index("idx_ml_predictions_shadow", "is_shadow", "created_at"),
    )


class ModelBetJournal(Base, UUIDPrimaryKeyMixin):
    """
    Statistical log of a side a model committed to.
    Shadows and zero-stake decisions are included. This is not the bankroll ledger.
    """

    __tablename__ = "model_bet_journal"

    event_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("events.id", ondelete="CASCADE"), nullable=False)
    sport_code: Mapped[str] = mapped_column(String(32), nullable=False)
    model_name: Mapped[str] = mapped_column(String(128), nullable=False)
    model_version: Mapped[str] = mapped_column(String(64), nullable=False)
    is_shadow: Mapped[bool] = mapped_column(Boolean, nullable=False)
    market: Mapped[str] = mapped_column(String(64), nullable=False)
    outcome: Mapped[str] = mapped_column(String(64), nullable=False)
    model_probability: Mapped[float] = mapped_column(Numeric(6, 4), nullable=False)
    bookmaker_odds: Mapped[float] = mapped_column(Numeric(10, 4), nullable=False)
    fair_odds: Mapped[float] = mapped_column(Numeric(10, 4), nullable=False)
    edge: Mapped[float] = mapped_column(Numeric(8, 4), nullable=False)
    expected_value: Mapped[float] = mapped_column(Numeric(8, 4), default=0, nullable=False)
    confidence: Mapped[float] = mapped_column(Numeric(6, 4), default=0, nullable=False)
    stake_amount: Mapped[float] = mapped_column(Numeric(12, 2), default=0, nullable=False)
    reason: Mapped[str] = mapped_column(String(1024), nullable=False)
    detail: Mapped[Dict[str, Any]] = mapped_column(JSONB, default=dict, nullable=False)
    decided_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utc_now, nullable=False)
    result_status: Mapped[str] = mapped_column(String(16), default="pending", nullable=False)
    result_winner: Mapped[Optional[str]] = mapped_column(String(64), nullable=True)
    settled_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)

    __table_args__ = (
        Index("idx_model_bet_journal_event", "event_id", "decided_at"),
        Index("idx_model_bet_journal_model", "model_name", "model_version", "decided_at"),
        Index(
            "uq_model_bet_journal_decision",
            "event_id",
            "model_name",
            "model_version",
            "is_shadow",
            "market",
            unique=True,
        ),
    )


class LLMDecision(Base, UUIDPrimaryKeyMixin):
    """
    Qualitative verdict and risk assessments from local LLM inference.
    """
    __tablename__ = "llm_decisions"

    event_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("events.id", ondelete="CASCADE"), nullable=False)
    llm_version: Mapped[str] = mapped_column(String(64), nullable=False)
    verdict: Mapped[str] = mapped_column(String(32), default="NEUTRAL", nullable=False)
    confidence_adjustment: Mapped[float] = mapped_column(Numeric(6, 4), default=0.0, nullable=False)
    injury_risk: Mapped[str] = mapped_column(String(32), default="unknown", nullable=False)
    fatigue_risk: Mapped[str] = mapped_column(String(32), default="unknown", nullable=False)
    reasoning: Mapped[str] = mapped_column(String(1024), nullable=False)
    raw_json: Mapped[Dict[str, Any]] = mapped_column(JSONB, default=dict, nullable=False)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utc_now, nullable=False)

    __table_args__ = (
        Index("idx_llm_decisions_event", "event_id", "created_at"),
    )


class ExternalPrediction(Base, UUIDPrimaryKeyMixin):
    """
    Pre-match predictions collected from external betting and analysis portals.
    Matched to Fonbet events when live odds appear. Expired after 24 hours if match never starts.
    """
    __tablename__ = "external_predictions"

    source_code: Mapped[str] = mapped_column(String(64), nullable=False)
    source_url: Mapped[str] = mapped_column(String(512), nullable=False, unique=True)
    sport_code: Mapped[str] = mapped_column(String(32), default="tennis", nullable=False)
    tournament_name: Mapped[str] = mapped_column(String(255), default="", nullable=False)

    raw_participant_a: Mapped[str] = mapped_column(String(255), nullable=False)
    raw_participant_b: Mapped[str] = mapped_column(String(255), nullable=False)
    canonical_participant_a: Mapped[str] = mapped_column(String(255), nullable=False)
    canonical_participant_b: Mapped[str] = mapped_column(String(255), nullable=False)

    estimated_start_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)

    market_type: Mapped[str] = mapped_column(String(64), default="match_winner", nullable=False)
    predicted_outcome: Mapped[str] = mapped_column(String(64), nullable=False)
    raw_prediction_text: Mapped[str] = mapped_column(String(255), nullable=False)
    recommended_odds: Mapped[Optional[float]] = mapped_column(Numeric(10, 4), nullable=True)

    author_name: Mapped[Optional[str]] = mapped_column(String(128), nullable=True)
    author_roi: Mapped[Optional[float]] = mapped_column(Numeric(8, 2), nullable=True)
    author_winrate: Mapped[Optional[float]] = mapped_column(Numeric(6, 2), nullable=True)
    reasoning_snippet: Mapped[Optional[str]] = mapped_column(String(2048), nullable=True)

    status: Mapped[str] = mapped_column(String(32), default="pending", nullable=False)
    matched_event_id: Mapped[Optional[uuid.UUID]] = mapped_column(ForeignKey("events.id", ondelete="SET NULL"), nullable=True)
    matched_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)

    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utc_now, nullable=False)
    expires_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)

    __table_args__ = (
        Index("idx_ext_pred_canonical", "canonical_participant_a", "canonical_participant_b", "estimated_start_at"),
        Index("idx_ext_pred_matched_event", "matched_event_id"),
        Index("idx_ext_pred_status_expires", "status", "expires_at"),
    )

