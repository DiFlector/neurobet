import uuid
from datetime import datetime
from typing import Optional, Dict, Any
from sqlalchemy import String, Boolean, Numeric, DateTime, ForeignKey, Index
from sqlalchemy.dialects.postgresql import UUID, JSONB
from sqlalchemy.orm import Mapped, mapped_column
from ..base import Base, UUIDPrimaryKeyMixin, utc_now


class FeatureSnapshot(Base):
    """
    TimescaleDB Hypertable partitioned on observed_at.
    Stores historical point-in-time feature vectors guaranteed without future data leakage.
    """
    __tablename__ = "feature_snapshots"

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    observed_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), primary_key=True, default=utc_now)
    event_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), nullable=False)
    sport_code: Mapped[str] = mapped_column(String(32), default="tennis", nullable=False)
    feature_version: Mapped[str] = mapped_column(String(32), default="1.0.0", nullable=False)
    features: Mapped[Dict[str, Any]] = mapped_column(JSONB, default=dict, nullable=False)

    __table_args__ = (
        Index("idx_feature_snapshots_event_time", "event_id", "observed_at"),
    )


class MLPrediction(Base, UUIDPrimaryKeyMixin):
    """
    Predictions generated by numeric ML models for match events.
    Matches user requirements for Tennis edge and expected value tracking.
    """
    __tablename__ = "ml_predictions"

    event_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("events.id", ondelete="CASCADE"), nullable=False)
    sport_code: Mapped[str] = mapped_column(String(32), default="tennis", nullable=False)
    model_version: Mapped[str] = mapped_column(String(64), nullable=False)
    market: Mapped[str] = mapped_column(String(64), default="match_winner", nullable=False)

    predicted_outcome: Mapped[str] = mapped_column(String(64), nullable=False)
    model_probability: Mapped[float] = mapped_column(Numeric(6, 4), nullable=False)
    bookmaker_odds: Mapped[float] = mapped_column(Numeric(10, 4), nullable=False)
    fair_odds: Mapped[float] = mapped_column(Numeric(10, 4), nullable=False)
    edge: Mapped[float] = mapped_column(Numeric(8, 4), nullable=False)
    expected_value: Mapped[float] = mapped_column(Numeric(8, 4), nullable=False)
    confidence: Mapped[float] = mapped_column(Numeric(6, 4), nullable=False)

    has_positive_edge: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    outcomes_detail: Mapped[Dict[str, Any]] = mapped_column(JSONB, default=dict, nullable=False)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utc_now, nullable=False)

    __table_args__ = (
        Index("idx_ml_predictions_event", "event_id", "created_at"),
        Index("idx_ml_predictions_edge", "has_positive_edge", "created_at"),
    )


class LLMDecision(Base, UUIDPrimaryKeyMixin):
    """
    Qualitative verdict and risk assessments from local LLM inference.
    """
    __tablename__ = "llm_decisions"

    event_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("events.id", ondelete="CASCADE"), nullable=False)
    llm_version: Mapped[str] = mapped_column(String(64), nullable=False)
    verdict: Mapped[str] = mapped_column(String(32), default="NEUTRAL", nullable=False)
    confidence_adjustment: Mapped[float] = mapped_column(Numeric(6, 4), default=0.0, nullable=False)
    injury_risk: Mapped[str] = mapped_column(String(32), default="unknown", nullable=False)
    fatigue_risk: Mapped[str] = mapped_column(String(32), default="unknown", nullable=False)
    reasoning: Mapped[str] = mapped_column(String(1024), nullable=False)
    raw_json: Mapped[Dict[str, Any]] = mapped_column(JSONB, default=dict, nullable=False)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utc_now, nullable=False)

    __table_args__ = (
        Index("idx_llm_decisions_event", "event_id", "created_at"),
    )
